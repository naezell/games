import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { gzipSync } from 'node:zlib';

const directory = new URL('./', import.meta.url);
const output = new URL('dist/', directory);
const read = (path) => readFile(new URL(path, directory), 'utf8');

const classic = (await read('index.html')).replace(
  'https://cdnjs.cloudflare.com/ajax/libs/three.js/r128/three.min.js',
  '/works/vendor/three.min.js'
);
const operations = await read('works/index.html');
const files = {
  '/': ['text/html', operations.replace(/<head(\s[^>]*)?>/i, '$&<base href="/works/">')],
  '/works/': ['text/html', operations],
  '/classic/': ['text/html', classic]
};

for (const [file, type] of [
  ['engine.mjs', 'text/javascript'],
  ['main.mjs', 'text/javascript'],
  ['save.mjs', 'text/javascript'],
  ['styles.css', 'text/css'],
  ['world.mjs', 'text/javascript'],
  ['vendor/three.min.js', 'text/javascript'],
  ['vendor/LICENSE', 'text/plain']
]) {
  files[`/works/${file}`] = [type, await read(`works/${file}`)];
}

for (const entry of Object.values(files)) {
  const [, body] = entry;
  const digest = createHash('sha256').update(body).digest('hex');
  entry.push(`"sha256-${digest}"`);
}

const worker = [
  '// Generated by frostfall-kitchen/build.mjs.',
  `const files = new Map(${JSON.stringify(Object.entries(files))});`,
  await read('cloudflare/handler.mjs')
].join('\n');

await mkdir(output, { recursive: true });
await writeFile(new URL('worker.mjs', output), worker);
await writeFile(new URL('metadata.json', output), await read('cloudflare/metadata.json'));
console.log(`Built dist/worker.mjs (${Buffer.byteLength(worker).toLocaleString('en-US')} bytes, ${gzipSync(worker).length.toLocaleString('en-US')} bytes gzipped).`);
